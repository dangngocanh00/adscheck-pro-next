test('supports Extended Payment settings and preview controls', async ({ page, isMobile }) => {
  await page.goto('/app/extended-payment')
  await expect(page).toHaveTitle('Extended Payment · Toolmeta')
  await expect(page.getByRole('heading', { name: 'Extended Payment' })).toBeVisible()
  const bubbleSwitch = page.getByRole('switch', { name: 'Bật tắt Bubble dữ liệu' })
  await expect(bubbleSwitch).toBeChecked()
  const promoClose = page.getByRole('button', { name: 'Đóng giới thiệu Toolmeta V8' })
  if (!isMobile && await promoClose.isVisible()) await promoClose.click()
  await page.getByRole('button', { name: 'Thanh Action' }).click()
  await expect(page.getByRole('button', { name: 'Thanh Action' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Tên tài khoản' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Tên tài khoản' }).click()
  await expect(page.getByRole('button', { name: 'Tên tài khoản' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Tên tài khoản' }).click()
  await page.getByRole('button', { name: 'In đậm' }).click()
  await page.getByLabel('Nội dung chữ ký').fill('Chữ ký đã lưu')
  await page.getByRole('button', { name: 'Lưu cài đặt' }).click()
  await page.reload()
  await expect(page.getByLabel('Nội dung chữ ký')).toHaveValue('Chữ ký đã lưu')
  await expect(page.getByRole('button', { name: 'In đậm' })).toHaveAttribute('aria-pressed', 'true')
  const saveStatus = page.locator('.ads-extended-save-status')
  await bubbleSwitch.press('Space')
  await expect(saveStatus).toContainText('Có thay đổi chưa lưu')
  await bubbleSwitch.press('Space')
  await expect(saveStatus).toContainText('Cấu hình khớp bản đã lưu')
  await page.getByRole('button', { name: 'Lưu cài đặt' }).click()
  await expect(saveStatus).toContainText('Đã lưu cấu hình mô phỏng')
  await bubbleSwitch.press('Space')
  await expect(page.getByText('Đang tắt', { exact: true })).toBeVisible()
  await expect(saveStatus).toContainText('Có thay đổi chưa lưu')
})

